"""Create (or re-create) the ML demo user with ~6 months of realistic synthetic expenses.

    python scripts/seed_ml_demo.py              # into database/spendly.db (or $SPENDLY_DB_PATH)
    python scripts/seed_ml_demo.py --db x.db    # into another database file

Log in as ml_demo@spendly.com / demo123 to see the forecast card, the ⚠️ badges and the chart.

Safe to re-run: it ONLY touches the user ml_demo@spendly.com. That user (and, through ON DELETE
CASCADE, only that user's expenses, income, budgets and "This is normal" marks) is deleted and
created again. No other user's rows are read or changed.

The data is generated by code with a fixed random seed, relative to today, so the current month
is always "in progress". Patterns: rent on the 1st, gym on the 3rd, electricity ~6th, recharge on
the 12th, internet on the 15th, Netflix on the 20th; weekday lunches / chai / commute; Saturday
dinners, movies and cabs; Sunday groceries; petrol every ~10 days; random shopping and pharmacy.
Plus SPIKES: 5 deliberate unusual expenses that the anomaly detector should catch
(evals/ml_eval.py measures that with precision / recall).
"""
import argparse
import os
import random
import sys
from datetime import date, timedelta

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PROJECT_DIR)

DEMO_EMAIL = "ml_demo@spendly.com"
DEMO_PASSWORD = "demo123"
DEMO_NAME = "ML Demo"
MONTHS_OF_HISTORY = 6
BUDGETS = [(None, 37000), ("Food", 10000)]
RANDOM_SEED = 42

# The deliberate unusual expenses: (days after the first day, amount, category, description).
# Each is placed late enough that its category already has >= 8 earlier expenses.
SPIKES = [
    (48, 5200, "Food", "Birthday party dinner"),
    (77, 2800, "Transport", "Airport cab"),
    (105, 7800, "Health", "Emergency dental treatment"),
    (130, 4500, "Entertainment", "Concert tickets"),
    (160, 32000, "Shopping", "New phone"),
]


def first_day(today):
    """The 1st of the month MONTHS_OF_HISTORY months before today's month."""
    year, month = today.year, today.month - MONTHS_OF_HISTORY
    while month <= 0:
        month, year = month + 12, year - 1
    return date(year, month, 1)


def build_expenses(today, seed=RANDOM_SEED):
    """Returns (expenses, spikes): lists of (amount, category, 'YYYY-MM-DD', description),
    oldest first, never after today. Same today + seed -> exactly the same data."""
    rng = random.Random(seed)
    start = first_day(today)
    out = []

    def add(day, amount, category, description):
        out.append((float(round(amount)), category, day.isoformat(), description))

    month_mood = {}
    day = start
    next_petrol = start + timedelta(days=rng.randint(0, 4))
    while day <= today:
        mood = month_mood.setdefault((day.year, day.month), rng.uniform(0.9, 1.1))
        weekday = day.weekday()          # 0 = Monday ... 6 = Sunday
        # --- fixed monthly items ---
        if day.day == 1:
            add(day, 15000, "Bills", "House rent")
        if day.day == 3:
            add(day, 1200, "Health", "Gym membership")
        if day.day == 6:
            add(day, rng.uniform(1300, 2300), "Bills", "Electricity bill")
        if day.day == 12:
            add(day, 299, "Bills", "Mobile recharge")
        if day.day == 15:
            add(day, 799, "Bills", "Internet bill")
        if day.day == 20:
            add(day, 199, "Entertainment", "Netflix subscription")
        # --- weekdays ---
        if weekday < 5:
            if rng.random() < 0.85:
                add(day, rng.uniform(110, 220) * mood, "Food", "Office lunch")
            if rng.random() < 0.5:
                add(day, rng.uniform(20, 70), "Food", "Chai and snacks")
            if rng.random() < 0.8:
                if rng.random() < 0.5:
                    add(day, rng.uniform(60, 150), "Transport", "Auto to office")
                else:
                    add(day, rng.uniform(40, 80), "Transport", "Metro")
            if weekday == 2 and rng.random() < 0.3:
                add(day, rng.uniform(150, 400), "Food", "Vegetables and fruits")
        # --- weekends ---
        if weekday == 5:
            if rng.random() < 0.8:
                add(day, rng.uniform(600, 1300) * mood, "Food", "Dinner with friends")
            if rng.random() < 0.4:
                add(day, rng.uniform(300, 750), "Entertainment", "Movie tickets")
            if rng.random() < 0.7:
                add(day, rng.uniform(150, 450), "Transport", "Cab")
        if weekday == 6:
            add(day, rng.uniform(700, 1500) * mood, "Food", "Groceries")
        # --- every ~10 days / now and then ---
        if day >= next_petrol:
            add(day, rng.uniform(500, 900), "Transport", "Petrol")
            next_petrol = day + timedelta(days=rng.randint(8, 12))
        if rng.random() < 0.08:
            add(day, rng.uniform(400, 2500), "Shopping",
                rng.choice(["Clothes", "Amazon order", "Household items", "Shoes"]))
        if rng.random() < 0.08:
            add(day, rng.uniform(120, 600), "Health", "Pharmacy")
        if rng.random() < 0.03:
            add(day, rng.uniform(200, 1000), "Other", rng.choice(["Gift for friend", "Donation"]))
        day += timedelta(days=1)

    spikes = []
    for offset, amount, category, description in SPIKES:
        when = start + timedelta(days=offset)
        if when <= today:
            spikes.append((float(amount), category, when.isoformat(), description))
    out = sorted(out + spikes, key=lambda e: e[2])   # stable: same-day order kept
    return out, spikes


def seed(db, today=None, seed_value=RANDOM_SEED):
    """(Re)create the demo user in the database `db` points at. Returns (user_id, spikes)."""
    today = today or date.today()
    db.init_db()
    existing = db.get_user_by_email(DEMO_EMAIL)
    if existing is not None:
        db.delete_user(existing["id"])   # only this user; CASCADE removes only their rows
    user_id = db.create_user(DEMO_NAME, DEMO_EMAIL, DEMO_PASSWORD)
    expenses, spikes = build_expenses(today, seed_value)
    db.add_expenses(user_id, expenses)
    for category, limit in BUDGETS:
        db.set_budget(user_id, category, limit)
    return user_id, spikes


def main():
    p = argparse.ArgumentParser(description="(Re)create the ML demo user ml_demo@spendly.com")
    p.add_argument("--db", help="database file (default: $SPENDLY_DB_PATH or database/spendly.db)")
    args = p.parse_args()
    if args.db:
        os.environ["SPENDLY_DB_PATH"] = os.path.abspath(args.db)
    sys.stdout.reconfigure(encoding="utf-8")   # ₹ on a Windows console
    import database.db as db   # after SPENDLY_DB_PATH is set
    user_id, spikes = seed(db)
    count = db.get_expense_summary(user_id)["count"]
    print(f"Database: {db.DB_PATH}")
    print(f"Demo user {DEMO_EMAIL} (password {DEMO_PASSWORD}) re-created with {count} expenses "
          f"from {first_day(date.today()):%d %b %Y} to today. Other users were not touched.")
    print("Deliberate unusual expenses:")
    for amount, category, day, description in spikes:
        print(f"  {day}  {category:<13} ₹{amount:>9,.0f}  {description}")


if __name__ == "__main__":
    main()
